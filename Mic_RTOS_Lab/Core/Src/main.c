/*
 * 麥克風 MP34DT01 (PDM) -> DFSDM1 Channel1 (讀 PE7 = DATIN2) -> Filter0 -> DMA1_Channel4 -> PCM_Buffer
 *
 * 時脈：DFSDM CKOUT = SYSCLK 80 MHz / 40 = 2 MHz   (MP34DT01 可接受 1 ~ 3.25 MHz)
 * 濾波：Sinc3, FOSR = 125, IOSR = 1               -> 取樣率 = 2 MHz / 125 = 16 kHz
 *
 * PCM_Buffer 有 PCM_BUFFER_LEN 個 sample，DMA 為 circular 模式：
 *   填滿前半 (top half)    -> HalfCplt callback -> toggle PIN1 (ARD_D8 = PB2)
 *   填滿後半 (bottom half) -> Cplt callback     -> toggle PIN2 (ARD_D9 = PA15)
 * 每半個 buffer 的時間 = (PCM_BUFFER_LEN/2) / 16 kHz = 256 / 16000 = 16 ms
 * PIN1、PIN2 各自每 32 ms toggle 一次 -> 方波週期 64 ms (15.625 Hz)，兩者相位差 16 ms
 * 用邏輯分析儀量到 PIN1 方波頻率 f 後反推取樣率：Fs = f * 2 * PCM_BUFFER_LEN
 */
